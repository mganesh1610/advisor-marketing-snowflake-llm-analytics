-- Snowflake + dbt Pre-Aggregated Advisor Single-View Data Model
-- Prevents 1-to-many join fan-out, enforces deterministic deduplication,
-- and normalizes UTC event timestamps to America/New_York business dates.

CREATE SCHEMA IF NOT EXISTS MARKETING_ANALYTICS.CORE;

-- 1. Deduplicated CRM Advisor Dimension (Salesforce / HubSpot unified)
CREATE OR REPLACE VIEW MARKETING_ANALYTICS.CORE.STG_ADVISOR_DEDUP AS
SELECT
    ADVISOR_ID,
    EMAIL_HASH_SHA256,
    FIRM_SEGMENT,
    CHANNEL_PREFERENCE,
    PRIMARY_TIMEZONE,
    CREATED_AT_UTC,
    UPDATED_AT_UTC
FROM MARKETING_ANALYTICS.RAW.CRM_ADVISORS
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY EMAIL_HASH_SHA256
    ORDER BY UPDATED_AT_UTC DESC, CREATED_AT_UTC ASC
) = 1;

-- 2. Pre-Aggregated Email & Campaign Engagement (1 row per advisor_id)
CREATE OR REPLACE VIEW MARKETING_ANALYTICS.CORE.STG_CAMPAIGN_PREAGG AS
SELECT
    ADVISOR_ID,
    COUNT(DISTINCT CAMPAIGN_TOUCH_ID) AS TOTAL_CAMPAIGN_TOUCHES,
    SUM(CASE WHEN EVENT_TYPE = 'EMAIL_OPEN' THEN 1 ELSE 0 END) AS EMAIL_OPENS,
    SUM(CASE WHEN EVENT_TYPE = 'EMAIL_CLICK' THEN 1 ELSE 0 END) AS EMAIL_CLICKS,
    MAX(CONVERT_TIMEZONE('UTC', 'America/New_York', EVENT_TS_UTC)::DATE) AS LAST_TOUCH_DATE_EST
FROM MARKETING_ANALYTICS.RAW.MARKETING_TOUCHES
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY CAMPAIGN_TOUCH_ID
    ORDER BY INGESTED_AT_UTC DESC
) = 1
GROUP BY ADVISOR_ID;

-- 3. Pre-Aggregated Event Attendance & Post-Event Activity (Cvent / Typeform)
CREATE OR REPLACE VIEW MARKETING_ANALYTICS.CORE.STG_EVENT_PREAGG AS
SELECT
    ADVISOR_ID,
    COUNT(DISTINCT EVENT_ID) AS EVENTS_ATTENDED,
    SUM(POST_EVENT_PLATFORM_LOGINS_14D) AS POST_EVENT_LOGINS_14D,
    SUM(PIPELINE_INFLUENCE_USD) AS ATTRIBUTED_PIPELINE_USD,
    MIN(CONVERT_TIMEZONE('UTC', 'America/New_York', EVENT_START_UTC)::DATE) AS FIRST_EVENT_DATE_EST
FROM MARKETING_ANALYTICS.RAW.EVENT_ATTENDANCE
GROUP BY ADVISOR_ID;

-- 4. Single View of the Advisor Mart (Zero Join Fan-Out Guaranteed)
CREATE OR REPLACE TABLE MARKETING_ANALYTICS.CORE.MART_ADVISOR_360 AS
SELECT
    a.ADVISOR_ID,
    a.FIRM_SEGMENT,
    a.CHANNEL_PREFERENCE,
    COALESCE(c.TOTAL_CAMPAIGN_TOUCHES, 0) AS TOTAL_CAMPAIGN_TOUCHES,
    COALESCE(c.EMAIL_OPENS, 0) AS EMAIL_OPENS,
    COALESCE(c.EMAIL_CLICKS, 0) AS EMAIL_CLICKS,
    c.LAST_TOUCH_DATE_EST,
    COALESCE(e.EVENTS_ATTENDED, 0) AS EVENTS_ATTENDED,
    COALESCE(e.POST_EVENT_LOGINS_14D, 0) AS POST_EVENT_LOGINS_14D,
    COALESCE(e.ATTRIBUTED_PIPELINE_USD, 0.00) AS ATTRIBUTED_PIPELINE_USD,
    e.FIRST_EVENT_DATE_EST
FROM MARKETING_ANALYTICS.CORE.STG_ADVISOR_DEDUP a
LEFT JOIN MARKETING_ANALYTICS.CORE.STG_CAMPAIGN_PREAGG c
    ON a.ADVISOR_ID = c.ADVISOR_ID
LEFT JOIN MARKETING_ANALYTICS.CORE.STG_EVENT_PREAGG e
    ON a.ADVISOR_ID = e.ADVISOR_ID;
